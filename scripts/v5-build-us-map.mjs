// One-off: turns the @svg-maps/usa state outlines (140 KB of 2-decimal
// relative line segments) into a compact, simplified polyline set for the /v5
// course finder map. Re-run after bumping the package:
//
//   node scripts/v5-build-us-map.mjs
//
// Output: components/v5/usMapData.ts (~25 KB). Shapes are simplified with
// Ramer–Douglas–Peucker at a 0.6 viewBox-unit tolerance — invisible at the
// ~420 px the map renders at, but it drops ~80% of the points.

import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const usa = require("@svg-maps/usa");
const map = usa.default || usa;

const TOLERANCE = 0.6;

/** Parse an M/m/L/l/H/h/V/v/Z/z-only path into absolute sub-paths. */
function toPolylines(d) {
  const tokens = d.match(/[MmLlHhVvZz]|-?\d*\.?\d+(?:e-?\d+)?/g) || [];
  const polys = [];
  let cur = [];
  let x = 0;
  let y = 0;
  let startX = 0;
  let startY = 0;
  let cmd = null;
  let i = 0;
  const num = () => parseFloat(tokens[i++]);
  while (i < tokens.length) {
    const t = tokens[i];
    if (/[A-Za-z]/.test(t)) {
      cmd = t;
      i++;
      if (cmd === "Z" || cmd === "z") {
        if (cur.length) polys.push(cur);
        cur = [];
        x = startX;
        y = startY;
        cmd = null;
      }
      continue;
    }
    if (!cmd) throw new Error("number before command");
    switch (cmd) {
      case "M":
        if (cur.length) polys.push(cur);
        cur = [];
        x = num();
        y = num();
        startX = x;
        startY = y;
        cur.push([x, y]);
        cmd = "L";
        break;
      case "m":
        if (cur.length) polys.push(cur);
        cur = [];
        x += num();
        y += num();
        startX = x;
        startY = y;
        cur.push([x, y]);
        cmd = "l";
        break;
      case "L":
        x = num();
        y = num();
        cur.push([x, y]);
        break;
      case "l":
        x += num();
        y += num();
        cur.push([x, y]);
        break;
      case "H":
        x = num();
        cur.push([x, y]);
        break;
      case "h":
        x += num();
        cur.push([x, y]);
        break;
      case "V":
        y = num();
        cur.push([x, y]);
        break;
      case "v":
        y += num();
        cur.push([x, y]);
        break;
      default:
        throw new Error(`Unsupported command ${cmd}`);
    }
  }
  if (cur.length) polys.push(cur);
  return polys;
}

function perpDistance(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len2 = dx * dx + dy * dy;
  if (len2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len2));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function rdp(points, eps) {
  if (points.length < 3) return points;
  let maxD = 0;
  let idx = 0;
  const a = points[0];
  const b = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDistance(points[i], a, b);
    if (d > maxD) {
      maxD = d;
      idx = i;
    }
  }
  if (maxD > eps) {
    const left = rdp(points.slice(0, idx + 1), eps);
    const right = rdp(points.slice(idx), eps);
    return left.slice(0, -1).concat(right);
  }
  return [a, b];
}

const fmt = (n) => String(Math.round(n * 10) / 10);

const states = map.locations.map((loc) => {
  const polys = toPolylines(loc.path)
    .map((p) => rdp(p, TOLERANCE))
    // Drop slivers (tiny islands) that simplify to nothing useful.
    .filter((p) => p.length >= 3);
  const d = polys
    .map((p) => `M${p.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L")}Z`)
    .join("");
  return { id: loc.id.toUpperCase(), name: loc.name, d };
});

const out = `// Generated by scripts/v5-build-us-map.mjs — do not edit by hand.
// Source: @svg-maps/usa (MIT). Simplified outlines for the /v5 state map.

export const US_MAP_VIEWBOX = ${JSON.stringify(map.viewBox)};

export type UsMapState = { id: string; name: string; d: string };

export const US_MAP_STATES: UsMapState[] = ${JSON.stringify(states, null, 0)
  .replace(/\{"id"/g, "\n  {\"id\"")
  .replace(/\]$/, "\n]")};
`;

writeFileSync(new URL("../components/v5/usMapData.ts", import.meta.url), out);
console.log(`wrote ${states.length} states, ${out.length} bytes`);
